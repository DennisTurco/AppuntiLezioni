package CorsoMinecraft.classi.esempioCompleto;

// classe che rappresenta un punto in un piano cartesiano xy
public class Point {
    private double x;
    private double y;

    public Point(double x, double y) {
        this.x = x;
        this.y = y;
    }

    public double getX() {
        return x;
    }
    public double getY() {
        return y;
    }
}
